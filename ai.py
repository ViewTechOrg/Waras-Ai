console = Console()


#Api sigma
API_URL = "https://api.siputzx.my.id/api/ai/blackboxai-pro?content="
CONFIG_FILE = "user_config.json"

def loading_animation(text="Menghubungi AI..."):
    with Live(Spinner("dots", text), refresh_per_second=10):
        time.sleep(2)

def type_text(text, delay=0.03):
    for char in text:
        print(char, end="", flush=True)
        time.sleep(delay)
    print()

def speak(text):
    os.system(f'espeak "{text}" 2>/dev/null')

def simpan_ke_file(user, ai, filename):
    if filename.endswith(".txt"):
        with open(filename, "a", encoding="utf-8") as f:
            f.write(f"User: {user}\nAI: {ai}\n\n")
    elif filename.endswith(".json"):
        data = {"user": user, "ai": ai}
        if os.path.exists(filename):
            with open(filename, "r+", encoding="utf-8") as f:
                try:
                    json_data = json.load(f)
                    if isinstance(json_data, list):
                        json_data.append(data)
                    else:
                        json_data = [json_data, data]
                except json.JSONDecodeError:
                    json_data = [data]
                f.seek(0)
                json.dump(json_data, f, indent=4)
        else:
            with open(filename, "w", encoding="utf-8") as f:
                json.dump([data], f, indent=4)

def chat(teks, espeak_on, auto_save_file=None):
    loading_animation()
    try:
        response = requests.get(API_URL + teks)
        response.raise_for_status()
        result = response.json().get("data", "Tidak ada balasan.")
    except Exception as e:
        result = f"[Gagal] Tidak bisa menghubungi AI: {e}"

    console.print(f"\n[bold green]AI:[/bold green] ", end="")
    type_text(result)

    if espeak_on:
        speak(result)

    if auto_save_file:
        simpan_ke_file(teks, result, auto_save_file)
    else:
        if Confirm.ask("Mau disimpan ke file?"):
            format_file = Prompt.ask("Format nama file (akhiri .txt atau .json)", default="hasil.txt")
            simpan_ke_file(teks, result, format_file)
            console.print(f"[green]Berhasil disimpan ke [bold]{format_file}[/bold][/green]")

def load_user_config():
    if os.path.exists(CONFIG_FILE):
        with open(CONFIG_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return None

def save_user_config(nama, espeak_on):
    with open(CONFIG_FILE, "w", encoding="utf-8") as f:
        json.dump({"nama": nama, "espeak": espeak_on}, f)

def main():
    parser = argparse.ArgumentParser(description="Chat AI dibuat Oleh Team ViewTechOrg, dan dev Fahad")
    parser.add_argument("-t", "--teks", help="Teks yang ingin dikirim")
    parser.add_argument("-es", "--espeak", help="Aktifkan espeak? (on/off)")
    parser.add_argument("-o", "--output", help="File output otomatis (.txt/.json)")
    args = parser.parse_args()

    console.print(Panel("Selamat datang di [bold cyan]Waras AI Chat[/bold cyan]", expand=False))

    config = load_user_config()
    if config:
        nama = config["nama"]
        espeak_on = config["espeak"]
    else:
        nama = Prompt.ask("Masukkan nama Anda")
        espeak_input = Prompt.ask("Aktifkan suara? (on/off)", choices=["on", "off"], default="off")
        espeak_on = espeak_input == "on"
        save_user_config(nama, espeak_on)

    console.print(f"Halo, [bold green]{nama}[/bold green]!")

    # Override jiks -es masuk
    if args.espeak:
        espeak_on = args.espeak.lower() == "on"

    if args.teks:
        chat(args.teks, espeak_on, args.output)
    else:
        while True:
            teks = Prompt.ask(f"[bold yellow]{nama}[/bold yellow]")
            if teks.lower() in ["exit", "quit"]:
                console.print("[italic]Keluar dari obrolan.[/italic]")
                break
            chat(teks, espeak_on, args.output)

if __name__ == "__main__":
    main()

